#!/usr/bin/env python3
"""Generates Sources/NexoLLM/Localization/Strings+XX.swift from scripts/i18n/<lang>.json.

Each JSON file maps the English template of an L("…", "…") call (interpolations as {0}, {1}, …) to its
translation. Only templates that still exist in the code are emitted; missing ones are listed (they fall back
to English at runtime) and make the script exit with status 1.

    scripts/gen-strings.py           regenerate all four tables
    scripts/gen-strings.py --check   only report missing / stale entries
"""
import importlib.util, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
spec = importlib.util.spec_from_file_location("extract", os.path.join(ROOT, "scripts", "extract-strings.py"))
extract = importlib.util.module_from_spec(spec)
spec.loader.exec_module(extract)

LANGS = {"es": "Spanish", "fr": "French", "de": "German", "pt": "Portuguese (Portugal)"}


def swift_literal(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def placeholders(s):
    return sorted(re.findall(r"\{\d+\}", s))


def main():
    check = "--check" in sys.argv
    templates = [p["en"] for p in extract.extract()]
    ok = True
    for code, name in LANGS.items():
        path = os.path.join(ROOT, "scripts", "i18n", code + ".json")
        table = json.load(open(path, encoding="utf-8")) if os.path.exists(path) else {}
        missing = [t for t in templates if t not in table]
        bad = [t for t in templates if t in table and placeholders(t) != placeholders(table[t])]
        stale = len([k for k in table if k not in set(templates)])
        print(f"{code}: {len(templates) - len(missing)}/{len(templates)} translated, {len(missing)} missing, "
              f"{len(bad)} placeholder mismatches, {stale} unused")
        for t in missing[:20]:
            print("   missing:", repr(t))
        for t in bad:
            print("   placeholders differ:", repr(t))
        if missing or bad:
            ok = False
        if check:
            continue
        lines = [
            "// Generated by scripts/gen-strings.py from scripts/i18n/%s.json. Do not edit by hand." % code,
            "// English template → %s." % name,
            "",
            "let strings%s: [String: String] = [" % code.upper(),
        ]
        for t in templates:
            if t in table and t not in bad:
                lines.append("    %s: %s," % (swift_literal(t), swift_literal(table[t])))
        lines.append("]")
        out = os.path.join(ROOT, "Sources", "NexoLLM", "Localization", "Strings+%s.swift" % code.upper())
        open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
